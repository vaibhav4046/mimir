def _synthesize_markdown(title: str, subtitle: str, sections: list[dict], rows: list[list[str]], report_md: str = "") -> str:
    if report_md and report_md.strip():
        return report_md.strip() + "\n"
    parts = [f"# {title}"]
    if subtitle:
        parts.append(f"> {subtitle}")
    for sec in sections:
        heading = str(sec.get("heading", "Section"))
        body = str(sec.get("body", ""))
        parts.append(f"## {heading}\n\n{body}")
    if rows and rows[0]:
        hdr = [str(c).replace("|", "/") for c in rows[0]]
        sep = ["---" for _ in hdr]
        tbl_lines = [
            "| " + " | ".join(hdr) + " |",
            "| " + " | ".join(sep) + " |",
        ]
        for row in rows[1:]:
            cells = [str(c).replace("\n", " ").replace("|", "/") for c in list(row)[: len(hdr)]]
            while len(cells) < len(hdr):
                cells.append("")
            tbl_lines.append("| " + " | ".join(cells) + " |")
        parts.append("## Data & Evidence Matrix\n\n" + "\n".join(tbl_lines))
    return "\n\n".join(parts) + "\n"


def build_md(out_path: Path, title: str, subtitle: str, sections: list[dict], rows: list[list[str]], report_md: str = "") -> dict:
    md_text = _synthesize_markdown(title, subtitle, sections, rows, report_md)
    out_path.write_text(md_text, encoding="utf-8")
    if len(md_text.strip()) < 5:
        raise RuntimeError("Generated Markdown report is empty")
    return {"chars": len(md_text), "lines": len(md_text.splitlines()), "sections": len(sections)}


def build_html(out_path: Path, title: str, subtitle: str, sections: list[dict], rows: list[list[str]], report_md: str = "") -> dict:
    import html as html_lib

    sec_html = []
    for sec in sections:
        h = html_lib.escape(str(sec.get("heading", "Section")))
        lines = str(sec.get("body", "")).splitlines()
        paras = "".join(f"<p>{html_lib.escape(ln)}</p>" for ln in lines if ln.strip())
        sec_html.append(f"<section class='card'><h2>{h}</h2>{paras}</section>")

    tbl_html = ""
    if rows and rows[0]:
        ths = "".join(f"<th>{html_lib.escape(str(c))}</th>" for c in rows[0])
        trs = []
        for row in rows[1:100]:
            tds = "".join(f"<td>{html_lib.escape(str(c))}</td>" for c in row)
            trs.append(f"<tr>{tds}</tr>")
        tbl_html = (
            "<section class='card'><h2>Comparative Evidence Matrix</h2>"
            f"<div class='table-wrap'><table><thead><tr>{ths}</tr></thead><tbody>{''.join(trs)}</tbody></table></div></section>"
        )

    md_raw = _synthesize_markdown(title, subtitle, sections, rows, report_md)
    html_doc = (
        "<!doctype html><html lang='en'><head><meta charset='utf-8'>"
        f"<title>{html_lib.escape(title)}</title>"
        "<style>"
        ":root{color-scheme:dark light;--bg:#0b1017;--card:#121923;--line:#263244;--fg:#e8edf5;--muted:#9fb0c7;--accent:#e6ab42;}"
        "@media print{:root{--bg:#ffffff;--card:#f8fafc;--line:#cbd5e1;--fg:#0f172a;--muted:#475569;--accent:#b45309;}}"
        "body{font-family:system-ui,-apple-system,Segoe UI,Roboto,sans-serif;background:var(--bg);color:var(--fg);margin:0;padding:36px 20px;line-height:1.6;}"
        "main{max-width:960px;margin:0 auto;}"
        "header{border-bottom:1px solid var(--line);padding-bottom:18px;margin-bottom:24px;}"
        "h1{margin:0 0 6px;font-size:28px;color:var(--fg);}"
        ".sub{color:var(--muted);font-size:14px;}"
        ".card{background:var(--card);border:1px solid var(--line);border-radius:12px;padding:18px 22px;margin-bottom:16px;}"
        "h2{margin:0 0 10px;font-size:18px;color:var(--accent);}"
        "p{margin:6px 0;font-size:14px;}"
        ".table-wrap{overflow-x:auto;}"
        "table{width:100%;border-collapse:collapse;font-size:13px;}"
        "th,td{border:1px solid var(--line);padding:8px 10px;text-align:left;vertical-align:top;}"
        "th{background:rgba(230,171,66,0.12);color:var(--accent);font-weight:600;}"
        "pre{white-space:pre-wrap;font-size:12px;background:rgba(0,0,0,0.22);padding:14px;border-radius:8px;overflow-x:auto;}"
        "</style></head><body><main>"
        f"<header><h1>{html_lib.escape(title)}</h1>"
        f"<div class='sub'>{html_lib.escape(subtitle or 'MIMIR Deep Research Report')}</div></header>"
        + "".join(sec_html)
        + tbl_html
        + f"<details class='card'><summary><strong>Full Source Markdown Report</strong></summary><pre>{html_lib.escape(md_raw)}</pre></details>"
        + "</main></body></html>"
    )
    out_path.write_text(html_doc, encoding="utf-8")
    return {"chars": len(html_doc), "sections": len(sections)}


def build_json(out_path: Path, title: str, subtitle: str, sections: list[dict], rows: list[list[str]], report_md: str = "") -> dict:
    from datetime import datetime, timezone

    payload = {
        "title": title,
        "subtitle": subtitle,
        "generatedAt": datetime.now(timezone.utc).isoformat(),
        "sections": sections,
        "rows": rows,
        "reportMarkdown": _synthesize_markdown(title, subtitle, sections, rows, report_md),
    }
    text = json.dumps(payload, indent=2, ensure_ascii=False)
    out_path.write_text(text, encoding="utf-8")
    return {"chars": len(text), "sections": len(sections), "rows": len(rows or [])}


def build_txt(out_path: Path, title: str, subtitle: str, sections: list[dict], rows: list[list[str]], report_md: str = "") -> dict:
    md_text = _synthesize_markdown(title, subtitle, sections, rows, report_md)
    out_path.write_text(md_text, encoding="utf-8")
    return {"chars": len(md_text), "lines": len(md_text.splitlines())}


def build_zip(out_path: Path, title: str, subtitle: str, sections: list[dict], rows: list[list[str]] = None, report_md: str = "") -> dict:
    slug = "".join(c if c.isalnum() or c in "-_" else "-" for c in title.lower()).strip("-") or "mimir-app"
    eff_rows = rows or []
    readme = _synthesize_markdown(title, subtitle, sections, eff_rows, report_md)
    csv_buf = io.StringIO()
    csv.writer(csv_buf).writerows(eff_rows if eff_rows else [["item", "status"], ["check", "ok"]])
    html_tmp = out_path.parent / "_tmp_report.html"
    build_html(html_tmp, title, subtitle, sections, eff_rows, report_md)
    html_body = html_tmp.read_text(encoding="utf-8")
    try:
        html_tmp.unlink()
    except OSError:
        pass
    json_payload = json.dumps({"title": title, "subtitle": subtitle, "sections": sections, "rows": eff_rows}, indent=2)
    with zipfile.ZipFile(str(out_path), "w", compression=zipfile.ZIP_DEFLATED) as zf:
        zf.writestr(f"{slug}/README.md", readme)
        zf.writestr(f"{slug}/index.html", html_body)
        zf.writestr(f"{slug}/report.html", html_body)
        zf.writestr(f"{slug}/dataset.csv", csv_buf.getvalue())
        zf.writestr(f"{slug}/report.json", json_payload)
        zf.writestr(
            f"{slug}/manifest.json",
            json.dumps(
                {
                    "title": title,
                    "subtitle": subtitle,
                    "sections": sections,
                    "files": ["README.md", "index.html", "report.html", "dataset.csv", "report.json"],
                },
                indent=2,
            ),
        )
    with zipfile.ZipFile(str(out_path), "r") as zf:
        names = zf.namelist()
    return {"entries": len(names), "files": names}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--spec", required=True, help="JSON spec file path")
    args = parser.parse_args()

    spec = json.loads(Path(args.spec).read_text(encoding="utf-8"))
    fmt = str(spec.get("format", "pdf")).lower()
    out_path = Path(spec["outPath"])
    out_path.parent.mkdir(parents=True, exist_ok=True)
    title = str(spec.get("title") or "MIMIR Foundry Artifact")
    subtitle = str(spec.get("subtitle") or "")
    sections = spec.get("sections") or [{"heading": "Executive Summary", "body": "Verified output produced locally by MIMIR Omni."}]
    rows = spec.get("rows") or []
    report_md = str(spec.get("reportMarkdown") or "")

    if fmt in ("png", "svg", "glb", "obj", "stl", "webm", "mp4", "gif", "wav", "music", "webapp", "game"):
        sys.path.insert(0, str(Path(__file__).resolve().parent))
        import creative_studio_builder as csb

        if fmt == "png":
            meta = csb.build_hd_png(out_path, spec)
        elif fmt == "svg":
            meta = csb.build_hd_svg(out_path, spec)
        elif fmt in ("glb", "obj", "stl"):
            meta = csb.build_3d_model(out_path, fmt, spec)
        elif fmt in ("webm", "mp4", "gif"):
            meta = csb.build_video(out_path, fmt, spec)
        elif fmt in ("wav", "music"):
            meta = csb.build_music_wav(out_path, spec)
        elif fmt == "webapp":
            meta = csb.build_webapp(out_path, spec)
        elif fmt == "game":
            meta = csb.build_game(out_path, spec)
    elif fmt == "pdf":
        meta = build_pdf(out_path, title, subtitle, sections, rows)
    elif fmt == "docx":
        meta = build_docx(out_path, title, subtitle, sections, rows)
    elif fmt == "md":
        meta = build_md(out_path, title, subtitle, sections, rows, report_md)
    elif fmt == "html":
        meta = build_html(out_path, title, subtitle, sections, rows, report_md)
    elif fmt == "json":
        meta = build_json(out_path, title, subtitle, sections, rows, report_md)
    elif fmt == "txt":
        meta = build_txt(out_path, title, subtitle, sections, rows, report_md)
    elif fmt == "pptx":
        meta = build_pptx(out_path, title, subtitle, sections, rows)
    elif fmt == "xlsx":
        meta = build_xlsx(out_path, title, subtitle, sections, rows)
    elif fmt == "zip":
        meta = build_zip(out_path, title, subtitle, sections, rows, report_md)
    elif fmt == "csv":
        eff = rows if rows else [["item", "status"], ["check", "ok"]]
        buf = io.StringIO()
        csv.writer(buf).writerows(eff)
        out_path.write_text(buf.getvalue(), encoding="utf-8")
        meta = {"rows": len(eff)}
    else:
        raise ValueError(f"Unsupported format: {fmt}")

    print(json.dumps({"ok": True, "format": fmt, "outPath": str(out_path), "sizeBytes": out_path.stat().st_size, "meta": meta}))


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        print(json.dumps({"ok": False, "error": str(exc)}), file=sys.stderr)
        sys.exit(1)
