from pathlib import Path


def _esc_xml(val: str) -> str:
    return str(val or "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def build_pdf(out_path: Path, title: str, subtitle: str, sections: list[dict], rows: list[list[str]]) -> dict:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import letter
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle
    import fitz

    doc = SimpleDocTemplate(
        str(out_path),
        pagesize=letter,
        title=title,
        author="MIMIR Omni Foundry",
        leftMargin=48,
        rightMargin=48,
        topMargin=52,
        bottomMargin=48,
    )
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "MimirTitle",
        parent=styles["Title"],
        textColor=colors.HexColor("#0f172a"),
        fontSize=19,
        spaceAfter=6,
    )
    sub_style = ParagraphStyle(
        "MimirSub",
        parent=styles["Normal"],
        textColor=colors.HexColor("#475569"),
        fontSize=10,
        spaceAfter=14,
    )
    h2_style = ParagraphStyle(
        "MimirH2",
        parent=styles["Heading2"],
        textColor=colors.HexColor("#1e293b"),
        spaceBefore=10,
        spaceAfter=4,
    )
    body_style = ParagraphStyle(
        "MimirBody",
        parent=styles["BodyText"],
        fontSize=9.5,
        leading=13,
        spaceAfter=4,
    )
    cell_hdr_style = ParagraphStyle(
        "MimirCellHdr",
        parent=styles["Normal"],
        fontSize=8,
        leading=10,
        textColor=colors.HexColor("#e6ab42"),
        fontName="Helvetica-Bold",
    )
    cell_body_style = ParagraphStyle(
        "MimirCellBody",
        parent=styles["Normal"],
        fontSize=8,
        leading=10,
        textColor=colors.HexColor("#0f172a"),
    )

    story = [Paragraph(_esc_xml(title), title_style), Paragraph(_esc_xml(subtitle or "Generated by MIMIR Omni Artifact Foundry"), sub_style)]
    for sec in sections:
        heading = str(sec.get("heading", "Section"))
        body = str(sec.get("body", ""))
        story.append(Paragraph(_esc_xml(heading), h2_style))
        for para in body.split("\n"):
            cleaned = para.strip()
            if cleaned:
                story.append(Paragraph(_esc_xml(cleaned), body_style))
        story.append(Spacer(1, 6))

    if rows and rows[0]:
        usable_w = letter[0] - 96
        num_cols = max(1, min(len(rows[0]), 7))
        trimmed_rows = [list(r)[:num_cols] for r in rows[:45]]
        wrapped_rows = []
        for r_idx, row in enumerate(trimmed_rows):
            c_style = cell_hdr_style if r_idx == 0 else cell_body_style
            wrapped_rows.append([Paragraph(_esc_xml(str(cell)[:220]), c_style) for cell in row])
        col_w = [usable_w / num_cols for _ in range(num_cols)]
        if num_cols >= 5:
            # Give wider space to topic/title/evidence columns while keeping ID/score compact
            weights = [0.7, 1.6, 0.9, 0.7, 2.2, 1.1, 1.0][:num_cols]
            total_w = sum(weights)
            col_w = [usable_w * (w / total_w) for w in weights]
        t = Table(wrapped_rows, colWidths=col_w, repeatRows=1)
        t.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0f172a")),
                    ("TEXTCOLOR", (0, 0), (-1, 0), colors.HexColor("#e6ab42")),
                    ("VALIGN", (0, 0), (-1, -1), "TOP"),
                    ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#94a3b8")),
                    ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f8fafc")]),
                    ("PADDING", (0, 0), (-1, -1), 5),
                ]
            )
        )
        story.append(Spacer(1, 8))
        story.append(t)

    doc.build(story)

    # Programmatic re-open verification via PyMuPDF
    pdf_doc = fitz.open(str(out_path))
    pages = len(pdf_doc)
    first_page_chars = len(pdf_doc[0].get_text() or "") if pages > 0 else 0
    pdf_doc.close()
    if pages < 1 or first_page_chars < 5:
        raise RuntimeError("Generated PDF failed non-empty content verification")
    return {"pages": pages, "extractedChars": first_page_chars}


def build_docx(out_path: Path, title: str, subtitle: str, sections: list[dict], rows: list[list[str]]) -> dict:
    from docx import Document

    doc = Document()
    doc.add_heading(title, level=0)
    if subtitle:
        p = doc.add_paragraph(subtitle)
        p.italic = True

    for sec in sections:
        doc.add_heading(str(sec.get("heading", "Section")), level=1)
        body = str(sec.get("body", ""))
        for line in body.split("\n"):
            stripped = line.strip()
            if not stripped:
                continue
            if stripped.startswith("- "):
                doc.add_paragraph(stripped[2:], style="List Bullet")
            else:
                doc.add_paragraph(stripped)

    if rows and rows[0]:
        table = doc.add_table(rows=len(rows), cols=len(rows[0]))
        table.style = "Table Grid"
        for r_idx, row in enumerate(rows):
            for c_idx, val in enumerate(row):
                table.cell(r_idx, c_idx).text = str(val)

    doc.save(str(out_path))

    # Re-open verification
    reopened = Document(str(out_path))
    para_count = len(reopened.paragraphs)
    if para_count < 1:
        raise RuntimeError("Generated DOCX has zero paragraphs")
    return {"paragraphs": para_count, "tables": len(reopened.tables)}


def build_pptx(out_path: Path, title: str, subtitle: str, sections: list[dict], rows: list[list[str]]) -> dict:
    from pptx import Presentation
    from pptx.dml.color import RGBColor
    from pptx.util import Inches, Pt

    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)

    blank_layout = prs.slide_layouts[6]

    def style_bg(slide, bg_rgb=(11, 16, 23)):
        bg = slide.background
        fill = bg.fill
        fill.solid()
        fill.fore_color.rgb = RGBColor(*bg_rgb)

    # Slide 1: Cover
    s0 = prs.slides.add_slide(blank_layout)
    style_bg(s0)
    tb = s0.shapes.add_textbox(Inches(0.9), Inches(2.1), Inches(11.5), Inches(2.8))
    tf = tb.text_frame
    tf.word_wrap = True
    p0 = tf.paragraphs[0]
    p0.text = title
    p0.font.size = Pt(38)
    p0.font.bold = True
    p0.font.color.rgb = RGBColor(230, 171, 66)

    p1 = tf.add_paragraph()
    p1.text = subtitle or "MIMIR Omni Presentation Deck"
    p1.font.size = Pt(18)
    p1.font.color.rgb = RGBColor(169, 238, 255)

    # Content slides
    for sec in sections:
        sl = prs.slides.add_slide(blank_layout)
        style_bg(sl, (16, 23, 34))
        hb = sl.shapes.add_textbox(Inches(0.8), Inches(0.6), Inches(11.7), Inches(0.9))
        hp = hb.text_frame.paragraphs[0]
        hp.text = str(sec.get("heading", "Overview"))
        hp.font.size = Pt(28)
        hp.font.bold = True
        hp.font.color.rgb = RGBColor(230, 171, 66)

        cb = sl.shapes.add_textbox(Inches(0.8), Inches(1.6), Inches(11.7), Inches(5.1))
        ctf = cb.text_frame
        ctf.word_wrap = True
        lines = [ln.strip() for ln in str(sec.get("body", "")).split("\n") if ln.strip()] or ["Verified section content."]
        for idx, line in enumerate(lines[:9]):
            cp = ctf.paragraphs[0] if idx == 0 else ctf.add_paragraph()
            cp.text = f"• {line.lstrip('- ')[:160]}"
            cp.font.size = Pt(16)
            cp.font.color.rgb = RGBColor(238, 241, 246)
            cp.space_after = Pt(8)

    if rows and rows[0]:
        sl = prs.slides.add_slide(blank_layout)
        style_bg(sl, (16, 23, 34))
        hb = sl.shapes.add_textbox(Inches(0.8), Inches(0.5), Inches(11.7), Inches(0.8))
        hp = hb.text_frame.paragraphs[0]
        hp.text = "Metrics & Structured Comparison"
        hp.font.size = Pt(26)
        hp.font.bold = True
        hp.font.color.rgb = RGBColor(230, 171, 66)

        n_rows = min(len(rows), 8)
        n_cols = min(len(rows[0]), 6)
        shape = sl.shapes.add_table(n_rows, n_cols, Inches(0.8), Inches(1.5), Inches(11.7), Inches(4.8))
        tbl = shape.table
        for r_i in range(n_rows):
            for c_i in range(n_cols):
                cell = tbl.cell(r_i, c_i)
                cell.text = str(rows[r_i][c_i])
                cell.fill.solid()
                cell.fill.fore_color.rgb = RGBColor(29, 43, 59) if r_i == 0 else RGBColor(19, 28, 39)
                for p in cell.text_frame.paragraphs:
                    p.font.size = Pt(13)
                    p.font.color.rgb = RGBColor(230, 171, 66) if r_i == 0 else RGBColor(226, 232, 240)

    prs.save(str(out_path))

    # Re-open verification
    reopened = Presentation(str(out_path))
    if len(reopened.slides) < 1:
        raise RuntimeError("Generated PPTX has zero slides")
    return {"slides": len(reopened.slides)}


def build_xlsx(out_path: Path, title: str, subtitle: str, sections: list[dict], rows: list[list[str]]) -> dict:
    import xlsxwriter

    wb = xlsxwriter.Workbook(str(out_path))
    ws_summary = wb.add_worksheet("Summary")
    ws_data = wb.add_worksheet("Data")

    hdr_fmt = wb.add_format({"bold": True, "bg_color": "#0F172A", "font_color": "#E6AB42", "border": 1})
    title_fmt = wb.add_format({"bold": True, "font_size": 15, "font_color": "#0F172A"})
    cell_fmt = wb.add_format({"border": 1})

    ws_summary.set_column(0, 0, 28)
    ws_summary.set_column(1, 1, 72)
    ws_summary.write(0, 0, title, title_fmt)
    ws_summary.write(1, 0, "Subtitle")
    ws_summary.write(1, 1, subtitle or "MIMIR Omni Workbook")

    row_cursor = 3
    ws_summary.write(row_cursor, 0, "Section", hdr_fmt)
    ws_summary.write(row_cursor, 1, "Details", hdr_fmt)
    row_cursor += 1
    for sec in sections:
        ws_summary.write(row_cursor, 0, str(sec.get("heading", "Section")), cell_fmt)
        ws_summary.write(row_cursor, 1, str(sec.get("body", "")), cell_fmt)
        row_cursor += 1

    eff_rows = rows if rows else [["Item", "Value"], ["Verified Checks", 1], ["Artifacts Built", 1]]
    for r_idx, row in enumerate(eff_rows):
        for c_idx, val in enumerate(row):
            ws_data.set_column(c_idx, c_idx, 20)
            fmt = hdr_fmt if r_idx == 0 else cell_fmt
            if r_idx > 0:
                try:
                    num = float(val)
                    ws_data.write_number(r_idx, c_idx, num, fmt)
                    continue
                except (ValueError, TypeError):
                    pass
            ws_data.write(r_idx, c_idx, str(val), fmt)

    # Add a deterministic formula row if numeric column 1 exists
    if len(eff_rows) >= 2 and len(eff_rows[0]) >= 2:
        total_row = len(eff_rows) + 1
        ws_data.write(total_row, 0, "Count Rows", hdr_fmt)
        ws_data.write_formula(total_row, 1, f"=COUNTA(A2:A{len(eff_rows)})", cell_fmt)

    wb.close()

    with zipfile.ZipFile(str(out_path), "r") as zf:
        names = zf.namelist()
        if "xl/workbook.xml" not in names:
            raise RuntimeError("Generated XLSX missing xl/workbook.xml")
    return {"sheets": 2, "dataRows": len(eff_rows), "zipEntries": len(names)}


def build_png(out_path: Path, title: str, subtitle: str, sections: list[dict]) -> dict:
    from PIL import Image, ImageDraw, ImageFont

    width, height = 1024, 576
    img = Image.new("RGBA", (width, height), (11, 16, 23, 255))
    draw = ImageDraw.Draw(img)

    # Subtle obsidian & brass pixel frame (flat matte geometric, no glossy neon)
    draw.rectangle([16, 16, width - 17, height - 17], outline=(212, 162, 67, 255), width=4)
    draw.rectangle([28, 28, width - 29, height - 29], outline=(58, 201, 255, 160), width=2)
    draw.rectangle([48, 126, width - 49, 130], fill=(212, 162, 67, 255))

    font_lg = ImageFont.load_default(size=32) if hasattr(ImageFont, "load_default") else ImageFont.load_default()
    font_md = ImageFont.load_default(size=18) if hasattr(ImageFont, "load_default") else ImageFont.load_default()
    font_sm = ImageFont.load_default(size=15) if hasattr(ImageFont, "load_default") else ImageFont.load_default()

    draw.text((48, 52), title[:48], fill=(242, 235, 220, 255), font=font_lg)
    draw.text((48, 96), (subtitle or "MIMIR Omni Graphic Artifact")[:72], fill=(169, 238, 255, 255), font=font_md)

    y = 160
    for idx, sec in enumerate(sections[:4]):
        draw.rectangle([48, y, width - 49, y + 84], fill=(18, 27, 40, 255), outline=(49, 68, 94, 255), width=2)
        draw.rectangle([48, y, 56, y + 84], fill=(58, 201, 255, 255) if idx % 2 == 0 else (212, 162, 67, 255))
        draw.text((72, y + 12), str(sec.get("heading", "Panel"))[:56], fill=(230, 171, 66, 255), font=font_md)
        body_line = str(sec.get("body", "")).replace("\n", " ")[:92]
        draw.text((72, y + 44), body_line, fill=(215, 223, 234, 255), font=font_sm)
        y += 98

    img.save(str(out_path), format="PNG")
    with Image.open(str(out_path)) as check:
        check.verify()
        dims = check.size
    return {"width": dims[0], "height": dims[1]}


