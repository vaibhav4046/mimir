import { PALETTE, PixelCanvas } from './pixel-engine.mjs';

/**
 * 16x16 crisp pixel-grid UI Icons for every existing Mimir control & state
 * Group folders: navigation / status / actions / empty-states
 */
function gridIcon(rows, extraLegend = {}, outline = true) {
  const tmp = new PixelCanvas(16, 16);
  const legend = {
    O: { color: PALETTE.OUTLINE, layer: 'outline' },
    G: { color: PALETTE.GOLD, layer: 'gold' },
    H: { color: PALETTE.GOLD_HI, layer: 'gold' },
    C: { color: PALETTE.CYAN, layer: 'ice' },
    I: { color: PALETTE.ICE_HI, layer: 'ice' },
    W: { color: PALETTE.WHITE, layer: 'base' },
    M: { color: PALETTE.MUTED, layer: 'base' },
    S: { color: PALETTE.STEEL, layer: 'base' },
    D: { color: PALETTE.SLATE_HI, layer: 'shadow' },
    K: { color: '#38b87c', layer: 'accent' },
    R: { color: PALETTE.CRIM, layer: 'accent' },
    ...extraLegend,
  };
  tmp.paintGrid(0, 0, rows, legend);
  let minX = 16;
  let maxX = -1;
  let minY = 16;
  let maxY = -1;
  for (let y = 0; y < 16; y++) {
    for (let x = 0; x < 16; x++) {
      if (tmp.get(x, y)) {
        if (x < minX) minX = x;
        if (x > maxX) maxX = x;
        if (y < minY) minY = y;
        if (y > maxY) maxY = y;
      }
    }
  }
  const c = new PixelCanvas(16, 16);
  if (maxX >= minX) {
    let dx = Math.round(7.5 - (minX + maxX) / 2);
    let dy = Math.round(7.5 - (minY + maxY) / 2);
    // Guarantee at least 1px outer transparent ring so autoOutline never touches corners (0,0)
    if (minX + dx < 1) dx = 1 - minX;
    if (maxX + dx > 14) dx = 14 - maxX;
    if (minY + dy < 1) dy = 1 - minY;
    if (maxY + dy > 14) dy = 14 - maxY;
    c.composite(tmp, dx, dy);
  }
  if (outline) c.autoOutline(PALETTE.OUTLINE);
  return c;
}

